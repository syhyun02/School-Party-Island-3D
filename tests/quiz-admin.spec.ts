import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {parseEnv} from 'node:util';
import {questions} from '../server/quiz';
test('redesigned island, private quiz feedback and authenticated teacher console',async({browser})=>{
 const student=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await student.newPage();const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173');
 await page.waitForTimeout(1800);
 await page.screenshot({path:'test-results/island-redesign.png',fullPage:true});
 await page.getByRole('button',{name:'루루 선택',exact:true}).click();
 await expect(page.locator('.avatar-preview b')).toHaveText('루루');
 await page.getByPlaceholder('어떤 이름으로 떠날까요?').fill('섬탐험가');
 await page.getByRole('button',{name:'섬으로 출발하기'}).click();
 await expect(page.getByText('교사의 시작 신호를 기다려 주세요.')).toBeVisible();
 await expect(page.locator('.lobby-avatar')).toContainText('루루');
 await page.locator('.lobby-avatar').getByRole('button',{name:'코코 선택',exact:true}).click();
 await expect(page.locator('.lobby-avatar')).toContainText('내 모험 친구 · 코코');
 await page.reload();await expect(page.locator('.lobby-avatar')).toContainText('내 모험 친구 · 코코');
 await page.getByRole('button',{name:'소리 끔',exact:true}).click();await expect(page.getByRole('button',{name:'소리 켬',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByRole('button',{name:'소리 켬',exact:true}).click();
 await page.getByRole('button',{name:'교육 퀴즈 연습'}).click();
 await expect(page.getByRole('dialog',{name:'교육 퀴즈'})).toBeVisible();
 const heading=await page.locator('.quiz-card h2').innerText();
 const q=questions.find(q=>q.question===heading)!;
 await page.locator('.quiz-options button').nth(q.answer).click();
 await expect(page.locator('.fact-card')).toContainText('정답이에요!');
 await page.screenshot({path:'test-results/quiz-feedback.png',fullPage:true});
 await page.getByRole('button',{name:'모험으로 돌아가기'}).click();
 const source=await student.request.get('http://127.0.0.1:5173/@fs/'+resolve('server/content/quizzes.json'));expect(source.status()).toBe(403);
 const denied=await student.request.get('http://127.0.0.1:5173/api/admin/status');expect(denied.status()).toBe(401);
 const teacher=await browser.newContext({viewport:{width:1440,height:1000}}),admin=await teacher.newPage();
 admin.on('pageerror',e=>errors.push(e.message));
 await admin.goto('http://127.0.0.1:5173/admin');
 await expect(admin.getByRole('heading',{name:'관리자 로그인'})).toBeVisible();
 const password=process.env.ADMIN_PASSWORD||parseEnv(readFileSync('.env','utf8')).ADMIN_PASSWORD;
 expect(Boolean(password)).toBe(true);
 await admin.getByLabel('비밀번호',{exact:true}).fill(password);
 await admin.getByRole('button',{name:'로그인',exact:true}).click();
 await expect(admin.getByRole('heading',{name:'학급 현황'})).toBeVisible();
 await admin.screenshot({path:'test-results/teacher-console.png',fullPage:true});
 await admin.getByRole('button',{name:'대기 중인 모든 방 시작'}).click();
 await expect(page.getByRole('button',{name:'주사위 굴리기'})).toBeVisible();
 await page.getByRole('button',{name:'주사위 굴리기'}).click();
 await expect(page.locator('.board-feedback')).toBeVisible();
 await page.screenshot({path:'test-results/dice-movement.png'});
 await admin.getByRole('button',{name:'일시정지',exact:true}).click();
 await expect(page.locator('.pause-overlay').or(page.getByText('일시정지',{exact:true}))).toBeVisible();
 await admin.getByRole('button',{name:'재개',exact:true}).click();
 await expect(page.locator('.pause-overlay')).toHaveCount(0);
 admin.once('dialog',d=>d.accept());
 await admin.getByRole('button',{name:'전체 종료 · 결과 발표'}).click();
 await expect(page.getByText(/최종 기여/)).toBeVisible();
 await admin.getByRole('button',{name:'로그아웃'}).click();
 await expect(admin.getByRole('heading',{name:'관리자 로그인'})).toBeVisible();
 expect(errors).toEqual([]);
 await student.close();await teacher.close();
});
